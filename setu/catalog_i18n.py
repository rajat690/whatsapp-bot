def overlay_label(english: str, language: str | None) -> str | None:
    """Marathi/Kannada label for an English catalog string, or None."""
    if language not in ("Marathi", "Kannada") or not english:
        return None
    pair = _MR_KN.get(english)
    if not pair:
        return None
    return pair[0] if language == "Marathi" else pair[1]
